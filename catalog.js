/** สร้างข้อมูลตำแหน่งบนเชลฟ์ 5 ชั้น (block = SH/TG/GD/HM · พิกัดมาจาก layout.js ชุดเดียวกับฉาก 3 มิติ) */
function shelfLoc(block, row, bay, level = 3, stock = 40) {
  const spot = shelfSpot(block, row, bay);
  return {
    kind: 'shelf',
    code: spot.code,
    zoneName: spot.zoneName,
    aisleLabel: `เชลฟ์ ${block}${row} · ${spot.title} · ตู้ที่ ${bay}`,
    levelLabel: SHELF_LEVEL_TXT[level] || SHELF_LEVEL_TXT[3],
    selfPick: true,
    stock,
    x: spot.x,
    y: 0.12 + (level - 1) * 0.46 + 0.2,
    z: spot.z,
    standX: spot.standX,
    standZ: spot.standZ,
  };
}
const sh = (row, bay, level, stock) => shelfLoc('SH', row, bay, level, stock);

