/** ค้นหาสินค้าด้วยคำค้น (รองรับพิมพ์หลายคำเว้นวรรค เช่น "สายไฟ 2.5" หรือ "ท่อ 4หุน" หรือรหัสช่อง "A2-03") */
export function filterProducts(query = '', catId = 'all') {
  const tokens = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  const hits = PRODUCTS.filter((p) => {
    if (catId !== 'all' && p.cat !== catId) return false;
    if (!tokens.length) return true;
    return tokens.every((tk) => p.searchText.includes(tk));
  });
  if (!tokens.length) return hits;
  // ชื่อสินค้าที่ตรงคำค้นขึ้นก่อนรายการที่ตรงเฉพาะคำค้นประกอบ (ค้น "ปูน" ต้องเจอปูนก่อนบล็อกฝังผนัง)
  const inName = (p) => { const n = p.name.toLowerCase(); return tokens.every((tk) => n.includes(tk)); };
  return [...hits.filter(inName), ...hits.filter((p) => !inName(p))];
}
