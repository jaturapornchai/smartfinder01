/** แปลงจำนวนเต็มสตางค์เป็นข้อความเงินบาท (ไม่ใช้ float) */
export function formatSatang(satang) {
  const n = BigInt(Math.round(Number(satang || 0)));
  const neg = n < 0n ? '-' : '';
  const abs = n < 0n ? -n : n;
  const baht = abs / 100n;
  const st = abs % 100n;
  const bahtStr = baht.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  if (st === 0n) return `${neg}฿${bahtStr}`;
  return `${neg}฿${bahtStr}.${st.toString().padStart(2, '0')}`;
}

