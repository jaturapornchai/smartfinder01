function seededRandom(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = seededRandom(0x2000b02);
const randInt = (lo, hi) => lo + Math.floor(rnd() * (hi - lo + 1));
function shuffled(list) {
  const a = list.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** แตก template 1 กลุ่มเป็นสินค้าทุกแบบ (ขนาด/รุ่น × ยี่ห้อ) สลับลำดับแล้ว · ราคาไล่ตามขนาดเป็นบาทจำนวนเต็ม แล้วคูณ 100 เป็นสตางค์ */
function expandTemplates(group) {
  const out = [];
  for (const [name, brands, variants, unit, minBaht, maxBaht, keywords] of group.items) {
    const span = maxBaht - minBaht;
    variants.forEach((v, vi) => brands.forEach((brand, bi) => {
      const baht = minBaht + Math.trunc((span * vi) / Math.max(1, variants.length - 1)) + Math.trunc((span * bi) / 40);
      out.push({ cat: group.cat, name: name.replace('{v}', v), brand, unit, priceSatang: baht * 100, keywords: `${keywords} ${v}`.toLowerCase() });
    }));
  }
  return shuffled(out);
}

